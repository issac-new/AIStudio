#!/usr/bin/env bash
# registry-render.sh — 注册表渲染与一致性校验（WP1）
#
# 用法:
#   bash registry-render.sh --check        # 六表 ↔ 代码 ↔ 夹具 三向一致性
#   bash registry-render.sh --facts        # 生成 assets/facts.generated.conf
#   bash registry-render.sh --dead-facts   # 列出零消费 FACT 键（供豁免登记）
#   bash registry-render.sh --dist         # 生成 UNIVERSAL_FILES 派生块（勿手改）
#   bash registry-render.sh --gates        # 由域源聚合三个 enforce 文件（WP6）
#   bash registry-render.sh --upstream-baseline # 输出 docs/upstream-baseline.md 状态表块
#   bash registry-render.sh --write-upstream-baseline # 就地重渲状态表块（勿手改区块）
#   bash registry-render.sh --lifecycle    # 能力生命周期/退役候选清单（只读报告）
#   bash registry-render.sh --capability-map # 预留给 references 视图生成（当前人工维护）
#   bash registry-render.sh --help
#
# 设计：注册表是权威源；本脚本只读 TSV，不 source 数据文件。
# bash 3.2 + BSD/GNU 双兼容；不使用关联数组、readarray、GNU sed -i。
set -euo pipefail

BASE="$(cd "$(dirname "$0")/.." && pwd)"
ROOT="$(cd "$BASE/.." && pwd)"
REG="${SWARM_REGISTRY_DIR:-$BASE/assets/registry}"
# shellcheck disable=SC1091
. "$BASE/assets/lib/conf.sh"
# shellcheck disable=SC1091
. "$BASE/assets/lib/log.sh"
TMPDIR_R="$(mktemp -d "${TMPDIR:-/tmp}/swarm-registry.XXXXXX")"
trap 'rm -rf "$TMPDIR_R"' EXIT
RC=0

say()  { printf '%s\n' "$*"; }
ok()   { log_ok "$*"; }
bad()  { log_bad "$*"; RC=1; }
warn() { log_warn "$*"; }

rows() { awk -F '\t' '!/^#/ && NF {n++} END{print n+0}' "$1"; }
source_for() {
  local p="$1" b c
  b="$(basename "$p")"
  for c in "$BASE/$p" "$BASE/assets/$b" "$BASE/assets/hooks/$b" "$BASE/assets/rules.d/$b" "$BASE/assets/ontology/$b" "$BASE/scripts/$b"; do
    if [[ -f "$c" ]]; then printf '%s' "$c"; return 0; fi
  done
  return 1
}
ids()  { awk -F '\t' '!/^#/ && NF {print $1}' "$1"; }
col()  { awk -F '\t' -v c="$2" '!/^#/ && NF {print $c}' "$1"; }

check_file() {
  local f="$1" want="$2" name="$3" n
  if [[ ! -f "$f" ]]; then bad "$name 缺失: $f"; return 1; fi
  n="$(rows "$f")"
  if [[ "$n" -eq "$want" ]]; then ok "$name $n 行"; else bad "$name 行数 $n ≠ $want"; fi
}

check_unique() {
  local f="$1" c="$2" name="$3" dup
  dup="$(col "$f" "$c" | sort | uniq -d | head -5)"
  if [[ -z "$dup" ]]; then ok "$name 列唯一"; else bad "$name 列重复: $(printf '%s' "$dup" | tr '\n' ' ')"; fi
}

check_set_equal() {
  local a="$1" b="$2" name="$3"
  sort -u "$a" > "$TMPDIR_R/a.sort"
  sort -u "$b" > "$TMPDIR_R/b.sort"
  local only_a only_b
  only_a="$(comm -23 "$TMPDIR_R/a.sort" "$TMPDIR_R/b.sort" | head -10 | tr '\n' ' ')"
  only_b="$(comm -13 "$TMPDIR_R/a.sort" "$TMPDIR_R/b.sort" | head -10 | tr '\n' ' ')"
  if [[ -z "$only_a" && -z "$only_b" ]]; then
    ok "$name 双向零孤儿"
  else
    if [[ -n "$only_a" ]]; then bad "$name 仅在代码/实存: $only_a"; fi
    if [[ -n "$only_b" ]]; then bad "$name 仅在注册表: $only_b"; fi
  fi
}

gen_facts() {
  local out="$1"
  local gtotal gcore garch gcomp gadv gfull gstd gm2 gm1
  local fw fwp refs rt rtd rtc rtm uf ufc
  local cv cvc cva cvcmp
  gtotal="$(rows "$REG/gates.tsv")"
  gcore="$(awk -F '\t' '!/^#/ && $5=="core"{n++} END{print n+0}' "$REG/gates.tsv")"
  garch="$(awk -F '\t' '!/^#/ && $5=="arch"{n++} END{print n+0}' "$REG/gates.tsv")"
  gcomp="$(awk -F '\t' '!/^#/ && $5=="compliance"{n++} END{print n+0}' "$REG/gates.tsv")"
  gadv="$(awk -F '\t' '!/^#/ && $5=="explicit"{n++} END{print n+0}' "$REG/gates.tsv")"
  gstd=$((gcore + garch))
  gfull=$((gtotal - gadv))
  gm2="$(awk -F '\t' '!/^#/ && $9=="M2"{n++} END{print n+0}' "$REG/gates.tsv")"
  gm1="$(awk -F '\t' '!/^#/ && $9=="M1"{n++} END{print n+0}' "$REG/gates.tsv")"
  fw="$(rows "$REG/frameworks.tsv")"
  fwp="$(ls "$BASE"/assets/framework-gates/*.sh 2>/dev/null | wc -l | tr -d ' ')"
  refs="$(rows "$REG/references.tsv")"
  rtd="$(awk -F '\t' '!/^#/ && $8=="deep"{n++} END{print n+0}' "$REG/runtimes.tsv")"
  rtc="$(awk -F '\t' '!/^#/ && $8=="cli"{n++} END{print n+0}' "$REG/runtimes.tsv")"
  rtm="$(awk -F '\t' '!/^#/ && $8=="method"{n++} END{print n+0}' "$REG/runtimes.tsv")"
  rt=$((rtd + rtc + rtm))
  uf="$(rows "$REG/dist.tsv")"
  ufc="$(awk -F '\t' '!/^#/ && $3=="lite"{n++} END{print n+0}' "$REG/dist.tsv")"
  cvc="$(conf_count_vars "$BASE/assets/precheck.conf")"
  cva="$(conf_count_vars "$BASE/assets/precheck.arch.conf")"
  cvcmp="$(conf_count_vars "$BASE/assets/precheck.compliance.conf")"
  cv=$((cvc + cva + cvcmp))
  {
    echo "# facts.generated.conf — GENERATED by scripts/registry-render.sh --facts"
    echo "# Do not edit. Source of truth: assets/registry/*.tsv + conf files."
    echo "FACT_GATES_TOTAL=$gtotal"
    echo "FACT_GATES_CORE=$gcore"
    echo "FACT_GATES_ARCH=$garch"
    echo "FACT_GATES_COMPLIANCE=$gcomp"
    echo "FACT_GATES_ADVISORY_ONLY=$gadv"
    echo "FACT_GATES_STANDARD=$gstd"
    echo "FACT_GATES_FULL=$gfull"
    echo "FACT_GATES_M2=$gm2"
    echo "FACT_GATES_M1=$gm1"
    echo "FACT_FRAMEWORKS=$fw"
    echo "FACT_FRAMEWORK_GATE_PAIR=$fwp"
    echo "FACT_REFERENCES=$refs"
    echo "FACT_RUNTIMES=$rt"
    echo "FACT_RUNTIMES_DEEP=$rtd"
    echo "FACT_RUNTIMES_CLI=$rtc"
    echo "FACT_RUNTIMES_METHOD=$rtm"
    echo "FACT_UNIVERSAL_FILES=$uf"
    echo "FACT_UNIVERSAL_FILES_CORE=$ufc"
    echo "FACT_CONF_VARS=$cv"
    echo "FACT_CONF_VARS_CORE=$cvc"
    echo "FACT_CONF_VARS_ARCH=$cva"
    echo "FACT_CONF_VARS_COMPLIANCE=$cvcmp"
  } > "$out"
}

facts_diff() {
  local gen="$TMPDIR_R/facts.generated"
  gen_facts "$gen"
  if [[ ! -f "$BASE/assets/facts.generated.conf" ]]; then
    warn "assets/facts.generated.conf 尚未生成；运行 --facts"
    return
  fi
  if diff -u "$BASE/assets/facts.generated.conf" "$gen" > "$TMPDIR_R/facts.diff" 2>&1; then
    ok "facts.generated.conf 与注册表一致"
  else
    bad "facts.generated.conf 过期；差异见下"
    sed -n '1,40p' "$TMPDIR_R/facts.diff" >&2 || true
  fi
}

gen_gates_to() {  # $1=输出目录
  local out="$1" enf gid domain
  for enf in strict warn advisory; do
    {
      printf '# GENERATED gates-%s.sh — source: assets/gates/ + gates.tsv; do not edit\n' "$enf"
      printf '# 源目录按 domain 组织；本文件按 gates.tsv 的 enforce 列聚合（WP6）。\n'
      [[ "$enf" == "advisory" ]] && printf '_AI_JUDGMENT=1\n'
      cat "$BASE/assets/gates/_lib.sh"
      awk -F '\t' -v e="$enf" '!/^#/ && $6==e {print $1"\t"$4}' "$REG/gates.tsv" \
        | while IFS=$'\t' read -r gid domain; do
            cat "$BASE/assets/gates/$domain/$gid.sh"
          done
    } > "$out/gates-$enf.sh"
  done
}

gates_block_check() {
  gen_gates_to "$TMPDIR_R"
  local enf
  for enf in strict warn advisory; do
    if diff -u "$BASE/assets/gates-$enf.sh" "$TMPDIR_R/gates-$enf.sh" > "$TMPDIR_R/gates-$enf.diff" 2>&1; then
      ok "gates-$enf.sh 与域源一致"
    else
      bad "gates-$enf.sh 过期；运行 registry-render.sh --gates"
      sed -n '1,20p' "$TMPDIR_R/gates-$enf.diff" >&2 || true
    fi
  done
}

enforce_decl_check() {
  # 声明 enforce ↔ gate-enforce-level.conf 有效分层（静态 + precheck override 重放）一致
  local conf="$BASE/assets/gate-enforce-level.conf" ov="$BASE/assets/precheck.sh" ebad="" fn lv eff
  [[ -f "$conf" ]] || { warn "gate-enforce-level.conf 缺失，跳过 enforce 对账"; return; }
  while IFS=$'\t' read -r gid flag fn dom tier enf cv fix claim notes; do
    if [[ "$gid" =~ ^# ]]; then continue; fi
    if [[ -z "$gid" ]]; then continue; fi
    lv="$(awk -F= -v k="$fn" '$1==k{print $2; exit}' "$conf")"
    if grep -q "_ENFORCE_OVERRIDE_K+=(check_${fn#check_})" "$ov" 2>/dev/null \
       || grep -qE "_ENFORCE_OVERRIDE_K+=.?\(?[^)]*\b${fn}\b" "$ov" 2>/dev/null; then
      eff="$(sed -n '/_ENFORCE_OVERRIDE_K+=.*'"$fn"'/,/.*)/p' "$ov" 2>/dev/null | grep -oE 'advisory|warn|strict' | head -1)"
      lv="${eff:-$lv}"
    fi
    if [[ "$lv" != "$enf" ]]; then
      ebad="$ebad $fn(声明=$enf/有效=${lv:-未登记})"
    fi
  done < "$REG/gates.tsv"
  if [[ -z "$ebad" ]]; then
    ok "enforce 声明 = gate-enforce-level.conf 有效分层"
  else
    bad "enforce 声明与有效分层分叉:${ebad}（登记 docs/enforce-waivers.md 或改声明）"
  fi
}

dist_block() {
  printf '# >>> swarm-yuan:dist-manifest >>> (generated from assets/registry/dist.tsv; do not edit)\n'
  printf 'UNIVERSAL_FILES=(\n'
  awk -F '\t' '!/^#/ && NF {printf "  \"%s|%s|%s\"\n", $1, $5, $3}' "$REG/dist.tsv"
  printf ')\n'
  printf '# <<< swarm-yuan:dist-manifest <<<\n'
}

dist_block_check() {
  local gen="$BASE/scripts/generate-skill.sh"
  if ! grep -q '^# >>> swarm-yuan:dist-manifest >>>' "$gen" 2>/dev/null; then
    warn "generate-skill.sh 尚无 dist-manifest 生成块（WP2 迁移中）"
    return
  fi
  awk '/^# >>> swarm-yuan:dist-manifest >>>/{f=1} f{print} /^# <<< swarm-yuan:dist-manifest <<</{f=0}' "$gen" > "$TMPDIR_R/dist.block"
  dist_block > "$TMPDIR_R/dist.gen"
  if diff -u "$TMPDIR_R/dist.block" "$TMPDIR_R/dist.gen" > "$TMPDIR_R/dist.diff" 2>&1; then
    ok "UNIVERSAL_FILES 生成块与 dist.tsv 一致"
  else
    bad "UNIVERSAL_FILES 生成块过期；运行 registry-render.sh --dist 生成并替换"
    sed -n '1,30p' "$TMPDIR_R/dist.diff" >&2 || true
  fi
}

upstream_baseline_block() {
  printf '<!-- >>> registry:runtimes >>> (generated from assets/registry/runtimes.tsv; do not edit) -->\n'
  printf '| 名称 | 仓库 | 许可证 | 当前基线 | 接入 | 证据 | 机器标记 |\n'
  printf '|---|---|---|---|---|---|---|\n'
  awk -F '\t' '!/^#/ && NF {printf "| %s | %s | %s | %s | %s | %s | baseline_status=%s |\n", $1, $2, $3, $7, $8, $9, $10}' "$REG/runtimes.tsv"
  printf '<!-- <<< registry:runtimes <<< -->\n'
}

upstream_baseline_write() {
  local doc="$BASE/docs/upstream-baseline.md" block="$TMPDIR_R/ub.write"
  [[ -f "$doc" ]] || { say "✗ 缺 docs/upstream-baseline.md（先建静态骨架）" >&2; exit 1; }
  upstream_baseline_block > "$block"
  awk -v blk="$block" '
    /^<!-- >>> registry:runtimes >>>/ {
      while ((getline line < blk) > 0) print line
      close(blk); skip=1; next
    }
    /^<!-- <<< registry:runtimes <<</ { skip=0; next }
    !skip { print }
  ' "$doc" > "$doc.new" && mv "$doc.new" "$doc"
  say "✓ 已重渲 docs/upstream-baseline.md 状态表块"
}

upstream_baseline_check() {
  local doc="$BASE/docs/upstream-baseline.md" max=40000 sz
  if [[ ! -f "$doc" ]]; then warn "docs/upstream-baseline.md 缺失；跳过状态表对账"; return; fi
  awk '/^<!-- >>> registry:runtimes >>>/{f=1} f{print} /^<!-- <<< registry:runtimes <<</{f=0}' "$doc" > "$TMPDIR_R/ub.block"
  upstream_baseline_block > "$TMPDIR_R/ub.gen"
  if diff -u "$TMPDIR_R/ub.block" "$TMPDIR_R/ub.gen" > "$TMPDIR_R/ub.diff" 2>&1; then
    ok "upstream-baseline 状态表与 runtimes.tsv 一致"
  else
    bad "upstream-baseline 状态表过期；运行 registry-render.sh --upstream-baseline"
    sed -n '1,30p' "$TMPDIR_R/ub.diff" >&2 || true
  fi
  sz="$(wc -c < "$doc" | tr -d ' ')"
  if [[ "$sz" -le "$max" ]]; then
    ok "upstream-baseline 状态表面积 ${sz}B ≤ ${max}B"
  else
    bad "upstream-baseline 状态表 ${sz}B > ${max}B（历史应迁 docs/research/upstream-changelog.md）"
  fi
  if grep -qE '^> \*\*(重核口径注|R[0-9]+ 轮注)' "$doc"; then
    bad "upstream-baseline 含逐轮历史头注；状态表只留当前值，历史迁 docs/research/upstream-changelog.md"
  else
    ok "upstream-baseline 未混入逐轮历史头注"
  fi
}

cmd_lifecycle() {
  say "▶ 能力生命周期候选（只读；退役须人工裁决）"
  say "## 门禁 claim<M2 或无夹具"
  awk -F '\t' '!/^#/ && NF && ($9!="M2" || $8=="-") {printf "  %-22s claim=%s fixture=%s\n", $1, $9, $8}' "$REG/gates.tsv"
  say "## 框架 claim<M2"
  awk -F '\t' '!/^#/ && NF && $9!="M2" {printf "  %-22s claim=%s status=%s\n", $1, $9, $10}' "$REG/frameworks.tsv"
  say "## 方法论：无消费节点/无触发（M1 是引用层常态，不逐条列）"
  local refcand
  refcand="$(awk -F '\t' '!/^#/ && NF && ($5=="" || $9=="") {printf "  %-34s consumer=%s trigger=%s\n", $1, $5, $9}' "$REG/references.tsv")"
  if [[ -n "$refcand" ]]; then printf '%s\n' "$refcand"; else say "  （无）"; fi
  say "## 运行时未整合或处于观察态"
  awk -F '\t' '!/^#/ && NF && ($8=="none" || $8=="source" || $10=="watch" || $10=="license-risk") {printf "  %-22s wiring=%s status=%s claim=%s\n", $1, $8, $10, $9}' "$REG/runtimes.tsv"
  say "## 宿主未实证"
  awk -F '\t' '!/^#/ && NF && $7=="rendered" {printf "  %-22s evidence=%s claim=%s\n", $1, $7, $8}' "$REG/hosts.tsv"
}

cmd_check() {
  say "▶ 注册表一致性（G26）"
  check_file "$REG/gates.tsv" 56 "gates"
  check_file "$REG/frameworks.tsv" 81 "frameworks"
  check_file "$REG/references.tsv" 57 "references"
  check_file "$REG/runtimes.tsv" 22 "runtimes"
  check_file "$REG/hosts.tsv" 11 "hosts"
  # dist: WP1 92；WP7 manifest 后 93；本体轮 +2 后 94；manifest 后 95；运维排障底座轮 +5 后 99；R138 +assets/lib/files.sh 后 100；合规检查能力轮 +3 后 103。必须与 facts 生成段一致。
  local dn; dn="$(rows "$REG/dist.tsv")"
  if [[ "$dn" -eq 99 || "$dn" -eq 100 || "$dn" -eq 103 || "$dn" -eq 104 ]]; then ok "dist $dn 行"; else bad "dist 行数 $dn ∉ {99,100,103,104}"; fi

  check_unique "$REG/gates.tsv" 1 "gates.id"
  check_unique "$REG/gates.tsv" 2 "gates.flag"
  check_unique "$REG/gates.tsv" 3 "gates.fn"
  check_unique "$REG/frameworks.tsv" 1 "frameworks.id"
  check_unique "$REG/references.tsv" 1 "references.id"
  check_unique "$REG/runtimes.tsv" 1 "runtimes.id"
  check_unique "$REG/hosts.tsv" 1 "hosts.id"
  check_unique "$REG/dist.tsv" 1 "dist.path"

  # 代码反查：门禁函数
  grep -h '^check_[a-z_]*()' "$BASE/assets/precheck.sh" "$BASE"/assets/gates-*.sh 2>/dev/null \
    | sed -E 's/^check_([a-z_]+)\(\).*/\1/' | sort -u > "$TMPDIR_R/gate_code"
  col "$REG/gates.tsv" 3 | sed -E 's/^check_//' | sort -u > "$TMPDIR_R/gate_reg"
  check_set_equal "$TMPDIR_R/gate_code" "$TMPDIR_R/gate_reg" "门禁函数"

  # 代码反查：框架片段
  ls "$BASE"/assets/framework-gates/*.sh 2>/dev/null | xargs -n1 basename 2>/dev/null | sed 's/\.sh$//' | sort -u > "$TMPDIR_R/fw_code" || true
  ids "$REG/frameworks.tsv" | sort -u > "$TMPDIR_R/fw_reg"
  check_set_equal "$TMPDIR_R/fw_code" "$TMPDIR_R/fw_reg" "框架片段"

  # 代码反查：references 实存
  ls "$BASE"/references/*.md 2>/dev/null | xargs -n1 basename 2>/dev/null | sed 's/\.md$//' | sort -u > "$TMPDIR_R/ref_code" || true
  ids "$REG/references.tsv" | sort -u > "$TMPDIR_R/ref_reg"
  check_set_equal "$TMPDIR_R/ref_code" "$TMPDIR_R/ref_reg" "references 实存"

  # 夹具存在性
  local missing=""
  while IFS=$'\t' read -r id flag fn dom tier enf cv fix claim notes; do
    if [[ "$id" =~ ^# ]]; then continue; fi
    if [[ -z "$id" ]]; then continue; fi
    if [[ "$fix" != "-" && ! -d "$BASE/$fix" ]]; then missing="$missing $id"; fi
  done < "$REG/gates.tsv"
  if [[ -z "$missing" ]]; then ok "门禁夹具目录齐全"; else bad "门禁夹具缺失:$missing"; fi

  missing=""
  while IFS=$'\t' read -r id fam rule gate fixture sig glob bins claim status; do
    if [[ "$id" =~ ^# ]]; then continue; fi
    if [[ -z "$id" ]]; then continue; fi
    if [[ ! -d "$BASE/$fixture" ]]; then missing="$missing $id"; fi
    if [[ ! -f "$BASE/$rule" ]]; then missing="$missing (rule:$id)"; fi
    if [[ ! -f "$BASE/$gate" ]]; then missing="$missing (gate:$id)"; fi
  done < "$REG/frameworks.tsv"
  if [[ -z "$missing" ]]; then ok "框架规则/片段/夹具齐全"; else bad "框架缺失:$missing"; fi

  # 门禁域源 ↔ gates.tsv 双向
  local gbad="" gid2 dom2 f
  while IFS=$'\t' read -r gid2 flag fn dom2 tier enf cv fix claim notes; do
    if [[ "$gid2" =~ ^# ]]; then continue; fi
    if [[ -z "$gid2" ]]; then continue; fi
    [[ -f "$BASE/assets/gates/$dom2/$gid2.sh" ]] || gbad="$gbad $gid2(源缺失)"
  done < "$REG/gates.tsv"
  ids "$REG/gates.tsv" | sort -u > "$TMPDIR_R/gate_ids"
  while IFS= read -r f; do
    [[ -n "$f" ]] || continue
    gid2="$(basename "$f" .sh)"
    grep -qx -- "$gid2" "$TMPDIR_R/gate_ids" || gbad="$gbad $gid2(未登记)"
  done < <(find "$BASE/assets/gates" -mindepth 2 -maxdepth 2 -name '*.sh' -type f 2>/dev/null)
  if [[ -z "$gbad" ]]; then ok "门禁域源 ↔ gates.tsv 双向"; else bad "门禁域源异常:$gbad"; fi

  # 宿主表：适配器实存 + detect 契约 + evidence 一致性
  local hbad=""
  while IFS=$'\t' read -r hid hdet hpath hschema hadapter hsupport hevidence hclaim hnotes; do
    if [[ "$hid" =~ ^# ]]; then continue; fi
    if [[ -z "$hid" ]]; then continue; fi
    [[ -f "$BASE/$hadapter" ]] || hbad="$hbad $hid:adapter"
    case "$hdet" in command:*|dir:*) ;; *) hbad="$hbad $hid:detect";; esac
    [[ -n "$hpath" ]] || hbad="$hbad $hid:path"
    case "$hevidence" in proven|rendered) ;; *) hbad="$hbad $hid:evidence";; esac
    case "$hclaim" in M3) [[ "$hevidence" == "proven" ]] || hbad="$hbad $hid:M3-not-proven";; esac
  done < "$REG/hosts.tsv"
  if [[ -z "$hbad" ]]; then ok "宿主适配器/检测契约/证据状态一致"; else bad "宿主表异常:$hbad"; fi

  # claim 合法性 + M2 证据
  local badclaim=""
  while IFS=$'\t' read -r id flag fn dom tier enf cv fix claim notes; do
    if [[ "$id" =~ ^# ]]; then continue; fi
    if [[ -z "$id" ]]; then continue; fi
    case "$claim" in M0|M1|M2|M3|M4) ;; *) badclaim="$badclaim $id:$claim";; esac
    if [[ "$claim" == "M2" && "$fix" == "-" ]]; then badclaim="$badclaim $id:M2-no-fixture"; fi
  done < "$REG/gates.tsv"
  while IFS=$'\t' read -r id fam rule gate fixture sig glob bins claim status; do
    if [[ "$id" =~ ^# ]]; then continue; fi
    if [[ -z "$id" ]]; then continue; fi
    case "$claim" in M0|M1|M2|M3|M4) ;; *) badclaim="$badclaim $id:$claim";; esac
  done < "$REG/frameworks.tsv"
  if [[ -z "$badclaim" ]]; then ok "claim 等级合法且有证据"; else bad "claim 异常:$badclaim"; fi

  # dist 路径存在性
  local miss=""
  while IFS=$'\t' read -r path aud tier mode cat off src req bytes; do
    if [[ "$path" =~ ^# ]]; then continue; fi
    if [[ -z "$path" ]]; then continue; fi
    case "$cat" in assets|gen|hook|rules|onto|ref|refd) ;; *) bad "dist 未知源类别: $path cat=$cat";; esac
    src="$(source_for "$path")" || { miss="$miss $path"; continue; }
    if [[ "$bytes" != "-" ]]; then
      sz="$(wc -c < "$src" | tr -d ' ')"
      if [[ "$bytes" != "$sz" ]]; then bad "dist bytes 漂移: $path 表 $bytes ≠ 实 ${sz}（重跑 --facts 或更新 references 后同步）"; fi
    fi
  done < "$REG/dist.tsv"
  if [[ -z "$miss" ]]; then ok "dist 路径全部实存"; else bad "dist 路径缺失:$miss"; fi
  dist_block_check
  gates_block_check
  enforce_decl_check
  upstream_baseline_check

  facts_diff

  if [[ "$RC" -eq 0 ]]; then say "✓ 注册表一致性通过"; else say "✗ 注册表一致性失败"; fi
  return "$RC"
}

cmd_dead_facts() {
  local facts="$BASE/assets/facts.conf" key hits waiver
  waiver="$BASE/docs/facts-waivers.md"
  printf '▶ 零消费 FACT 键扫描（执行面：*.sh/*.bat/*.yml/*.json；docs 不计消费）\n' >&2
  while IFS= read -r key; do
    [[ -z "$key" ]] && continue
    hits="$(grep -rl --include='*.sh' --include='*.bat' --include='*.yml' --include='*.json' \
      --exclude='facts.conf' --exclude='facts.generated.conf' --exclude-dir='registry' \
      -- "$key" "$BASE/assets" "$BASE/scripts" "$BASE/tests" "$ROOT/verifier/v1" 2>/dev/null \
      | grep -v '/self-check.sh$' | head -1 || true)"
    if [[ -z "$hits" ]]; then
      if grep -v '_fk_exempt' "$BASE/scripts/self-check.sh" 2>/dev/null | grep -c -- "$key" >/dev/null 2>&1; then
        hits="self-check"
      fi
    fi
    if [[ -z "$hits" ]]; then
      if [[ -f "$waiver" ]] && grep -q -- "$key" "$waiver"; then
        :
      else
        printf '%s\n' "$key"
      fi
    fi
  done < <(grep -E '^FACT_[A-Z0-9_]+=' "$facts" | sed -E 's/=.*//' | sort -u)
}

