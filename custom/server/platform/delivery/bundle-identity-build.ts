// bundle 身份构建侧装配（P1 round-2：spec §4.3-1/§4.4-3 接线清偿）。
//
// 职责：把两份既有事实源——注入 manifest v2（.overlay-injected.json：baseline.treeOids
// + patches[].{name,sha256}，Task 3/4 数据面）与 runtime 资产清单（dist/server/
// runtime-assets.json，Task 7 数据面）——装配成 BundleIdentityInput，经
// computeBundleIdentity（同目录纯函数，单一摘要语义）产出 bundleId，并渲染确定性
// 产物文件 dist/server/bundle-identity.txt（构建与发布门共用：release:gate 读取并
// 拦截缺席/过期身份——发布门不得无 bundle 身份通过）。
//
// canonicalRuntimeManifestJson 与 scripts/platform/lib/runtime-assets.mjs 的
// canonicalManifestJson 是同一语义的 TS/mjs 双实现（构建侧 mjs 与服务端 TS 分属两个
// 加载面），逐字节一致性由 bundle-identity-build.test.ts 的 parity 用例锁死。
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname } from 'node:path'
import { computeBundleIdentity, type AssetDigest, type BundleIdentityInput, type PatchDigest, type VendorBaselines } from './bundle-identity'

/** 注入 manifest v2 的最小读面（只取身份绑定所需字段，缺席如实 null）。 */
interface InjectionManifestLike {
  schemaVersion?: number
  baseline?: { treeOids?: Record<string, string | null> } | null
  patches?: Array<{ name?: string; sha256?: string }> | null
}

interface RuntimeManifestLike {
  schemaVersion?: number
  assets?: Array<{ rel?: string; sha256?: string }> | null
}

export interface ReleaseIdentity {
  bundleId: string
  input: BundleIdentityInput
}

/** runtime 清单 canonical 序列化（与 runtime-assets.mjs canonicalManifestJson 同语义：
 * schemaVersion + rel 排序后的原始资产对象逐字段保留——含 bytes 等，双实现逐字节一致
 * 由 parity 用例锁死，勿在一侧增删字段）。 */
export function canonicalRuntimeManifestJson(manifest: RuntimeManifestLike): string {
  const assets = [...(manifest?.assets ?? [])]
    .filter((a) => typeof a?.rel === 'string' && typeof a?.sha256 === 'string')
    .sort((a, b) => (a.rel! < b.rel! ? -1 : a.rel! > b.rel! ? 1 : 0))
  return JSON.stringify({ schemaVersion: manifest?.schemaVersion, assets })
}

function toPatchDigests(patches: InjectionManifestLike['patches']): PatchDigest[] {
  return (patches ?? [])
    .filter((p) => typeof p?.name === 'string' && typeof p?.sha256 === 'string')
    .map((p) => ({ name: p.name!, sha256: p.sha256! })) // series 序保留（数组序即注入计划序）
}

function toAssetDigests(assets: RuntimeManifestLike['assets']): AssetDigest[] {
  return (assets ?? [])
    .filter((a) => typeof a?.rel === 'string' && typeof a?.sha256 === 'string')
    .map((a) => ({ rel: a.rel!, sha256: a.sha256! }))
}

/**
 * 装配发布身份（纯函数：不触盘、不触 git）。
 * commit 由调用方传入（构建/发布门各自取真实 HEAD）。
 */
export function releaseIdentityFromManifests(input: {
  commit: string
  injectionManifest: InjectionManifestLike
  runtimeManifest: RuntimeManifestLike
}): ReleaseIdentity {
  const treeOids = input.injectionManifest?.baseline?.treeOids ?? {}
  const vendorBaselines: VendorBaselines = {
    'hermes-studio': typeof treeOids['hermes-studio'] === 'string' ? treeOids['hermes-studio'] : null,
    'hermes-agent': typeof treeOids['hermes-agent'] === 'string' ? treeOids['hermes-agent'] : null,
    zcode: typeof treeOids.zcode === 'string' ? treeOids.zcode : null,
  }
  const identityInput: BundleIdentityInput = {
    commit: input.commit,
    vendorBaselines,
    patchDigests: toPatchDigests(input.injectionManifest?.patches),
    runtimeManifestDigest: createHash('sha256').update(canonicalRuntimeManifestJson(input.runtimeManifest)).digest('hex'),
    assetDigests: toAssetDigests(input.runtimeManifest?.assets),
  }
  return { bundleId: computeBundleIdentity(identityInput), input: identityInput }
}

const digestOf = (s: string) => createHash('sha256').update(s).digest('hex')

/** 产物文件渲染：固定行序、无时间戳（同输入同字节——发布门可复算对账）。 */
export function renderBundleIdentityFile(identity: ReleaseIdentity): string {
  const i = identity.input
  return [
    '# bundle-identity: generated by build.mjs from injection manifest v2 + runtime-assets manifest (deterministic)',
    `bundleId: ${identity.bundleId}`,
    `commit: ${i.commit}`,
    `vendorBaseline.hermes-studio: ${i.vendorBaselines['hermes-studio'] ?? 'null'}`,
    `vendorBaseline.hermes-agent: ${i.vendorBaselines['hermes-agent'] ?? 'null'}`,
    `vendorBaseline.zcode: ${i.vendorBaselines.zcode ?? 'null'}`,
    `patches: ${i.patchDigests.length} sha256:${digestOf(JSON.stringify(i.patchDigests))}`,
    `runtimeManifest: sha256:${i.runtimeManifestDigest} assets:${i.assetDigests.length}`,
    `assets: sha256:${digestOf(JSON.stringify(i.assetDigests))}`,
    '',
  ].join('\n')
}

export interface WriteBundleIdentityArgs {
  commit: string
  injectionManifestPath: string
  runtimeManifestPath: string
  outFile: string
}

/** 读两份清单 → 装配 → 落盘产物（坏输入向上抛，不写半份产物）。 */
export function writeBundleIdentity(args: WriteBundleIdentityArgs): ReleaseIdentity {
  const parse = (p: string): unknown => JSON.parse(readFileSync(p, 'utf8'))
  const identity = releaseIdentityFromManifests({
    commit: args.commit,
    injectionManifest: parse(args.injectionManifestPath) as InjectionManifestLike,
    runtimeManifest: parse(args.runtimeManifestPath) as RuntimeManifestLike,
  })
  mkdirSync(dirname(args.outFile), { recursive: true })
  writeFileSync(args.outFile, renderBundleIdentityFile(identity))
  return identity
}
